class I18nState {
  locale = $state<Locale>('en');

  get isChinese(): boolean {
    return this.locale === 'zh-CN';
  }

  initialize(): void {
    if (typeof window === 'undefined') return;
    const saved = window.localStorage.getItem(STORAGE_KEY);
    const preferred = saved === 'en' || saved === 'zh-CN'
      ? saved
      : window.navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
    this.setLocale(preferred);
  }

  setLocale(locale: Locale): void {
    this.locale = locale;
    if (typeof document !== 'undefined') document.documentElement.lang = locale;
    if (typeof window !== 'undefined') window.localStorage.setItem(STORAGE_KEY, locale);
  }

  t(key: string, values: Record<string, string | number> = {}): string {
    const template = (this.locale === 'zh-CN' ? zh : en)[key] ?? en[key] ?? key;
    return Object.entries(values).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      template
    );
  }

  label(value: string): string {
    return labels[this.locale][value]
      ?? value.replaceAll('-', ' ').replaceAll('_', ' ').replace(/^./, (letter) => letter.toUpperCase());
  }

  reason(code: string): string {
    return reasons[this.locale][code] ?? code;
  }

  dynamic(value: string): string {
    return dynamicLabels[this.locale][value] ?? value;
  }

  date(unixSeconds: number, includeTime = false): string {
    return new Intl.DateTimeFormat(this.locale === 'zh-CN' ? 'zh-CN' : 'en-GB', {
      dateStyle: 'medium',
      ...(includeTime ? { timeStyle: 'short' as const } : {})
    }).format(new Date(unixSeconds * 1_000));
  }
}

